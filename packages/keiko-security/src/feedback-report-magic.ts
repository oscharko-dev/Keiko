function startsWith(bytes: Uint8Array, signature: readonly number[], offset = 0): boolean {
  return signature.every((byte, index) => bytes[offset + index] === byte);
}

export function hasUtf8Bom(bytes: Uint8Array): boolean {
  return startsWith(bytes, UTF8_BOM);
}

function isWebP(bytes: Uint8Array, offset: number): boolean {
  return (
    startsWith(bytes, [0x52, 0x49, 0x46, 0x46], offset) &&
    startsWith(bytes, [0x57, 0x45, 0x42, 0x50], offset + 8)
  );
}

function isSvg(bytes: Uint8Array, offset: number): boolean {
  const prefix = [bytes[offset], bytes[offset + 1], bytes[offset + 2], bytes[offset + 3]];
  return (
    prefix[0] === 0x3c &&
    prefix[1] !== undefined &&
    prefix[2] !== undefined &&
    prefix[3] !== undefined &&
    String.fromCharCode(prefix[1], prefix[2], prefix[3]).toLowerCase() === "svg"
  );
}

export function hasKnownFeedbackMagic(bytes: Uint8Array): boolean {
  const offset = hasUtf8Bom(bytes) ? UTF8_BOM.length : 0;
  return (
    MAGIC_SIGNATURES_V1.some((signature) => startsWith(bytes, signature, offset)) ||
    isWebP(bytes, offset) ||
    isSvg(bytes, offset)
  );
}
