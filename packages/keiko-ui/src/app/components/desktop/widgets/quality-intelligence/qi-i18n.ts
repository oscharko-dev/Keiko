export type QiMessageKey = keyof typeof QI_EN_MESSAGES;
export type I18nTranslate = (key: QiMessageKey, values?: MessageValues) => string;
type QiMessageCatalog = Readonly<Record<QiMessageKey, string>>;

function catalogFor(locale: Locale): QiMessageCatalog {
  return locale === "de" ? QI_DE_MESSAGES : QI_EN_MESSAGES;
}

function interpolate(template: string, values: MessageValues = {}): string {
  return template.replace(/\{([a-zA-Z0-9_]+)\}/gu, (match, name: string) => {
    const value = values[name];
    return value === undefined ? match : String(value);
  });
}

export function translateQi(locale: Locale, key: QiMessageKey, values?: MessageValues): string {
  const catalog = catalogFor(locale);
  return interpolate(catalog[key] ?? QI_EN_MESSAGES[key], values);
}

export function useQiTranslate(): I18nTranslate {
  const locale = useLocale();
  return useMemo<I18nTranslate>(() => {
    const catalog = catalogFor(locale);
    return (key, values) => interpolate(catalog[key] ?? QI_EN_MESSAGES[key], values);
  }, [locale]);
}
