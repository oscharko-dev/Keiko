// PR #3394 landed on `dev` by SQUASH, so its reviewed source head is not reachable from any
// branch or tag and a clone that never fetched `refs/pull/3394/head` simply does not carry that
// object -- every CI checkout included, `fetch-depth: 0` notwithstanding, because depth 0 clones
// every ref, not every orphaned commit. `checkToolCatalogMigrationCloseout` resolves that head
// against real Git and fails closed when it cannot, which is correct: the closeout is a deliberate
// LOCAL qualification run and `arch:check` deliberately invokes the conformance gate without
// `--closeout`. These two assertions are the only place the closeout runs where the object may be
// absent, so these assertions mirror the real Git-dependent source/current identity phase through
// the production function instead of re-deriving its digest formula. Every deterministic closeout
// phase remains live, so any unrelated defect still fails these tests in either environment.
async function closeoutFailuresThisCloneCanReach(root = ROOT) {
  const record = JSON.parse(readFileSync(join(root, H1_PROVENANCE_PATH), "utf8"));
  const { currentHead } = record;
  const failures = [];
  if (!isAncestorOfDev(currentHead, root, execFileSync)) {
    failures.push(
      `H1 handoff evidence unreachable: landedDevCommit ${currentHead} is not an ancestor of dev`,
    );
  }
  failures.push(...(await realSourceHeadFailures(root, record, execFileSync)));
  // Since ADR-0175 v1.3 the same clone dependency reaches one step further: a producer change is
  // admitted through an owner-issued lineage whose entries name their own `sourceCommit`. Those
  // commits live on the integration PR's branch, so a checkout that clones every ref resolves them
  // and a DEPTH-LIMITED one does not (`node-26-compatibility` takes `ref: github.sha` without
  // `fetch-depth: 0`, while the coverage lanes clone in full). The gate is right to fail closed on
  // a commit it cannot resolve — that is what stops a fabricated entry — so this expectation asks
  // the production function what THIS clone can see, exactly as it already does for the H1 record.
  failures.push(...(await producerLineageFailures(root, record)));
  return failures;
}

