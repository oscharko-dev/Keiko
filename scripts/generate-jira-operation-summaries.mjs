// Generates the one-line plain summary of every Jira operation that `jira.discover` ranks and returns
// (#4357). The summary is the first sentence of the operation descriptor's description, produced by the
// production `plainOperationSummary`; discovery reads this table instead of building all 443 descriptors
// at its first call. `jiraOperationSummaries.test.ts` fails when the table drifts from the descriptors.
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { format, resolveConfig } from "prettier";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const atlassian = join(repoRoot, "packages", "keiko-server", "dist", "atlassian");
const { jiraOperationContracts } = await import(
  pathToFileURL(join(atlassian, "jiraManagedProvider.js")).href
);
const { plainOperationSummary } = await import(
  pathToFileURL(join(atlassian, "jiraOperationSummary.js")).href
);
const target = join(
  repoRoot,
  "packages",
  "keiko-server",
  "src",
  "atlassian",
  "jiraOperationSummaries.generated.ts",
);

const entries = jiraOperationContracts()
  .map((contract) => [
    contract.definition.tool,
    plainOperationSummary(contract.declaration.descriptor.description),
  ])
  .sort(([left], [right]) => left.localeCompare(right, "en-US"));
const body = entries
  .map(([tool, summary]) => `  ${JSON.stringify(tool)}: ${JSON.stringify(summary)},`)
  .join("\n");
const source = `// Generated by scripts/generate-jira-operation-summaries.mjs; do not edit by hand (#4357).
// The first sentence of each Jira operation descriptor, for \`jira.discover\`.
export const JIRA_OPERATION_SUMMARIES: Readonly<Record<string, string>> = {
${body}
};
`;
const options = (await resolveConfig(target)) ?? {};
writeFileSync(target, await format(source, { ...options, parser: "typescript", filepath: target }));
process.stdout.write(`jira operation summaries: ${String(entries.length)} written\n`);
