#!/usr/bin/env node
// Measured test-file times for duration-balanced Vitest shards (quality-gate hardening plan
// 2026-11-21, P5):
//
//   gh run download <green ci.yml run> --pattern 'coverage-blob-*' --dir <dir>
//   node scripts/generate-vitest-durations.mjs [--root <checkout>] <dir>/*/blob-*.json
//
// Reads the blob reports the coverage shards upload and writes, per repository-relative test file,
// the seconds its worker spent on it (import, setup and tests) to
// scripts/lib/vitest-file-durations.json, which scripts/lib/vitest-duration-sequencer.mjs reads.
// Times from a hosted runner are the ones that matter: the shards run there. A refresh only moves
// files between shards; it can never change which files run. Keys are relative to the checkout the
// blobs were measured in (`--root`, by default the hosted runner's), never to a prefix the measured
// files happen to share: a scripts-only blob would otherwise key `a.test.mjs` where the sequencer
// looks up `scripts/__tests__/a.test.mjs`. A file outside that checkout fails the generation.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { isMainModule } from "./lib/is-main-module.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = join(ROOT, "scripts", "lib", "vitest-file-durations.json");
const { parse } = createRequire(import.meta.url)("flatted");

/** Seconds a worker spent on one file of a blob report. */
export function fileSeconds(file) {
  const parts = [
    file.result?.duration,
    file.collectDuration,
    file.setupDuration,
    file.prepareDuration,
    file.environmentLoad,
  ];
  return parts.reduce((sum, value) => sum + (Number.isFinite(value) ? value : 0), 0) / 1000;
}

/** The checkout directory of `actions/checkout` on a hosted Linux runner for this repository. */
export const HOSTED_CHECKOUT = "/home/runner/work/Keiko/Keiko";

/**
 * Per repository-relative file, the largest time any blob measured (a file both coverage runs
 * execute, or that several CI runs measured, counts with its slower run), rounded to a tenth of a
 * second, keys sorted.
 */
export function durationsFromBlobs(blobs, root = HOSTED_CHECKOUT) {
  const files = blobs.flatMap((blob) => blob[1] ?? []);
  const prefix = root.endsWith("/") ? root : `${root}/`;
  const seconds = new Map();
  for (const file of files) {
    if (typeof file.filepath !== "string" || !file.filepath.startsWith(prefix)) {
      throw new TypeError(
        `a measured file lies outside the checkout ${root}: ${String(file.filepath)}`,
      );
    }
    const key = file.filepath.slice(prefix.length);
    seconds.set(key, Math.max(seconds.get(key) ?? 0, fileSeconds(file)));
  }
  return Object.fromEntries(
    [...seconds]
      .sort(([a], [b]) => (a < b ? -1 : Number(a > b)))
      .map(([key, value]) => [key, Math.round(value * 10) / 10]),
  );
}

/** `--root <checkout>` (default the hosted runner's) and the blob report paths. */
export function generationPlan(argv) {
  const index = argv.indexOf("--root");
  const root = index === -1 ? HOSTED_CHECKOUT : argv[index + 1];
  if (typeof root !== "string" || !root.startsWith("/")) {
    throw new TypeError("--root must name the absolute checkout the blobs were measured in");
  }
  const paths = index === -1 ? argv : argv.filter((_, at) => at !== index && at !== index + 1);
  if (paths.length === 0) throw new TypeError("pass the blob-*.json reports of a green run");
  return { root, paths };
}

/**
 * Writes the durations of the given blobs and returns the exit code; 1 is a document that could not
 * be generated. `output`, `log` and `error` are seams for the in-process tests; the command line
 * writes the checked-in document and uses the console.
 */
export function main(argv, { output = OUTPUT, log = console.log, error = console.error } = {}) {
  try {
    const { root, paths } = generationPlan(argv);
    const blobs = paths.map((path) => parse(readFileSync(path, "utf8")));
    const files = durationsFromBlobs(blobs, root);
    const document = {
      $comment:
        "Generated by scripts/generate-vitest-durations.mjs from hosted-runner coverage blobs; seconds per test file.",
      files,
    };
    writeFileSync(output, `${JSON.stringify(document, null, 2)}\n`);
    log(`vitest-durations: ${String(Object.keys(files).length)} files written to ${output}`);
    return 0;
  } catch (error_) {
    error(`vitest-durations: could not generate — ${error_.message}`);
    return 1;
  }
}

if (isMainModule(import.meta.url)) process.exitCode = main(process.argv.slice(2));
