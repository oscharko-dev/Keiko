#!/usr/bin/env bash
# Review gate lab (Epic #4130, Issue #4138): serves the review model pair on this Mac with
# mlx_lm.server and LiteLLM, and runs the offline review gate against it. Commands and the full
# procedure are in README.md next to this file.
#
#   lab.sh setup 4bit|8bit                       install the tools, download the pinned pair, write configs
#   lab.sh check 4bit|8bit                       validate the generated gateway config with Keiko's parser
#   lab.sh start 4bit|8bit                       start the pair and the gateway (loopback only)
#   lab.sh stop                                  stop them
#   lab.sh run 4bit|8bit development|seeds       wait for memory, start, run the gate, stop
#
# Everything it creates lives in $KEIKO_REVIEW_LAB (default ~/keiko-review-lab), outside the
# checkout. The gateway key is generated once into $KEIKO_REVIEW_LAB/.env (mode 600), reaches the
# Keiko server only through the environment and is never printed.
set -euo pipefail

LAB=${KEIKO_REVIEW_LAB:-$HOME/keiko-review-lab}
CHECKOUT=$(cd "$(dirname "$0")/../../../.." && pwd)
REVIEWER_PORT=${KEIKO_REVIEW_LAB_REVIEWER_PORT:-8080}
COUNTER_PORT=${KEIKO_REVIEW_LAB_COUNTER_PORT:-8081}
GATEWAY_PORT=${KEIKO_REVIEW_LAB_GATEWAY_PORT:-4000}
# What a running `run` started. These are global so that its EXIT trap still sees them, and the
# trap stops only what this invocation started (R4130-041 to R4130-044).
WATCHDOG_PID=
GATE_PID=
STARTED=
OWNS_LOCK=
# The versions the 4-bit holdout and seed runs of 2026-11 used.
MLX_LM_VERSION=0.32.2
LITELLM_VERSION=1.106.6

# Pinned model builds: Hugging Face repository and revision, the Keiko model id, and the memory
# (GB that macOS can reclaim) a run waits for. The pair's weights are 38.8 GB at 4 bit and 71.5 GB
# at 8 bit; each server also keeps a bounded prompt cache (4 GB and 6 GB).
pair() {
  case "$1" in
    4bit)
      REVIEWER_REPO=mlx-community/Qwen3.6-35B-A3B-4bit
      REVIEWER_REVISION=38740b847e4cb78f352aba30aa41c76e08e6eb46
      REVIEWER_ID=qwen3.6-35b-a3b-4bit
      COUNTER_REPO=mlx-community/gemma-4-31b-it-4bit
      COUNTER_REVISION=696d436c404745a59f30e4939a658162b0a9e57f
      COUNTER_ID=gemma-4-31b-it-4bit
      MIN_FREE_GB=${KEIKO_REVIEW_LAB_MIN_FREE_GB:-42}
      ;;
    8bit)
      REVIEWER_REPO=mlx-community/Qwen3.6-35B-A3B-8bit
      REVIEWER_REVISION=e06a74e6236a60c8367e1a3214e83d8b61b637b0
      REVIEWER_ID=qwen3.6-35b-a3b-8bit
      COUNTER_REPO=mlx-community/gemma-4-31b-it-8bit
      COUNTER_REVISION=f5f3dc92ab4af76724c36c21eb6bedadb3a851be
      COUNTER_ID=gemma-4-31b-it-8bit
      MIN_FREE_GB=${KEIKO_REVIEW_LAB_MIN_FREE_GB:-84}
      ;;
    *)
      echo "lab: unknown quantization '${1:-}' (use 4bit or 8bit)" >&2
      exit 2
      ;;
  esac
  QUANT=$1
}

model_path() { # repo revision -> local snapshot path (downloads on first use)
  "$LAB/venv/bin/hf" download "$1" --revision "$2" --quiet | tail -n 1
}

write_litellm_config() { # reviewer-path counter-path
  cat > "$LAB/litellm-$QUANT.yaml" <<EOF
# Generated by lab.sh setup $QUANT. Loopback only; the master key comes from the environment.
model_list:
  - model_name: $REVIEWER_ID
    litellm_params:
      model: openai/$1
      api_base: http://127.0.0.1:$REVIEWER_PORT/v1
      api_key: mlx-local
    model_info:
      max_input_tokens: 131072
      max_output_tokens: 8192
      supports_function_calling: true
  - model_name: $COUNTER_ID
    litellm_params:
      model: openai/$2
      api_base: http://127.0.0.1:$COUNTER_PORT/v1
      api_key: mlx-local
    model_info:
      max_input_tokens: 131072
      max_output_tokens: 8192
      supports_function_calling: true
general_settings:
  master_key: os.environ/LITELLM_MASTER_KEY
litellm_settings:
  drop_params: true
  request_timeout: 1800
router_settings:
  num_retries: 0
EOF
}

write_gateway_config() {
  node --input-type=module - "$LAB/gateway-$QUANT.json" "$GATEWAY_PORT" "$REVIEWER_ID" "$COUNTER_ID" <<'EOF'
import { writeFileSync } from "node:fs";
const [path, port, ...ids] = process.argv.slice(2);
const capability = (id) => ({
  id,
  kind: "chat",
  contextWindow: 131072,
  maxOutputTokens: 8192,
  toolCalling: true,
  structuredOutput: false,
  streaming: true,
  supportsImageInput: false,
  supportsDocumentInput: false,
  supportsSeeding: false,
  supportsResponseFormat: false,
  supportsInfilling: false,
  workflowEligible: true,
  costClass: "low",
  latencyClass: "standard",
  throughputHint: "local-lab",
  preferredUseCases: ["coding"],
  knownLimitations: [],
});
const providers = ids.map((modelId) => ({
  modelId,
  baseUrl: `http://127.0.0.1:${port}/v1`,
  apiKeyHeaderName: "authorization",
  timeoutMs: 900000,
  maxRetries: 1,
  retryBaseDelayMs: 1000,
  capability: capability(modelId),
}));
const config = {
  schemaVersion: 2,
  providers,
  capabilities: ids.map(capability),
  circuitBreaker: { failureThreshold: 5, cooldownMs: 30000, halfOpenProbes: 2 },
};
writeFileSync(path, `${JSON.stringify(config, null, 2)}\n`, { mode: 0o600 });
EOF
}

cmd_setup() {
  pair "$1"
  mkdir -p "$LAB/logs"
  chmod 700 "$LAB"
  if [ ! -x "$LAB/venv/bin/mlx_lm.server" ]; then
    python3 -m venv "$LAB/venv"
    "$LAB/venv/bin/pip" install --quiet "mlx-lm==$MLX_LM_VERSION" "litellm[proxy]==$LITELLM_VERSION"
  fi
  echo "lab: downloading $REVIEWER_REPO and $COUNTER_REPO at their pinned revisions"
  local reviewer_path counter_path
  reviewer_path=$(model_path "$REVIEWER_REPO" "$REVIEWER_REVISION")
  counter_path=$(model_path "$COUNTER_REPO" "$COUNTER_REVISION")
  if [ ! -f "$LAB/.env" ]; then
    (umask 077 && printf 'LITELLM_MASTER_KEY=sk-%s\n' "$(openssl rand -hex 24)" > "$LAB/.env")
  fi
  write_litellm_config "$reviewer_path" "$counter_path"
  write_gateway_config
  if [ ! -d "$LAB/keiko/.git" ]; then
    git clone --quiet https://github.com/oscharko-dev/Keiko.git "$LAB/keiko"
  fi
  echo "lab: $QUANT ready in $LAB (Reviewer $REVIEWER_ID, Counter-checker $COUNTER_ID)"
}

cmd_check() {
  pair "$1"
  # The gate passes the key through KEIKO_DEFAULT_API_KEY, so the check does too.
  # shellcheck source=/dev/null
  (set -a && . "$LAB/.env" && set +a &&
    KEIKO_DEFAULT_API_KEY="$LITELLM_MASTER_KEY" node --input-type=module - "$CHECKOUT" \
      "$LAB/gateway-$QUANT.json" <<'EOF'
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { join } from "node:path";
const [checkout, path] = process.argv.slice(2);
const gateway = await import(
  pathToFileURL(join(checkout, "packages/keiko-model-gateway/dist/index.js")).href
);
const env = { KEIKO_DEFAULT_API_KEY: process.env.KEIKO_DEFAULT_API_KEY };
const config = gateway.parseGatewayConfig(JSON.parse(readFileSync(path, "utf8")), env);
console.log(`lab: gateway config valid, models ${config.providers.map((p) => p.modelId).join(", ")}`);
EOF
  )
}

listening() { lsof -nP -iTCP:"$1" -sTCP:LISTEN -t >/dev/null 2>&1; }

serve() { # port path pidname log temp top-p top-k chat-template-args cache-bytes
  # Sampling follows each model card (#4138 dev-2, dev-3): the Reviewer runs Qwen's non-thinking
  # mode. One request at a time, a 512-token prefill step and a byte cap on the prompt cache keep
  # both servers inside the GPU limit (#4138 dev-6); none of them changes what a request generates.
  nohup "$LAB/venv/bin/mlx_lm.server" --host 127.0.0.1 --port "$1" --model "$2" \
    --max-tokens 8192 --prompt-cache-size 2 --prompt-cache-bytes "$9" \
    --decode-concurrency 1 --prompt-concurrency 1 --prefill-step-size 512 \
    --temp "$5" --top-p "$6" --top-k "$7" --chat-template-args "$8" >> "$LAB/logs/$4" 2>&1 &
  echo $! > "$LAB/logs/$3"
}

cmd_start() {
  pair "$1"
  [ -f "$LAB/litellm-$QUANT.yaml" ] || { echo "lab: run 'lab.sh setup $QUANT' first" >&2; exit 1; }
  # R4130-042: every port is checked before any server starts, so a refusal leaves nothing running.
  local port
  for port in "$REVIEWER_PORT" "$COUNTER_PORT" "$GATEWAY_PORT"; do
    if listening "$port"; then
      echo "lab: port $port is already in use; stop that server or set KEIKO_REVIEW_LAB_*_PORT" >&2
      exit 1
    fi
  done
  export HF_HUB_OFFLINE=1
  local reviewer_path counter_path
  reviewer_path=$(model_path "$REVIEWER_REPO" "$REVIEWER_REVISION")
  counter_path=$(model_path "$COUNTER_REPO" "$COUNTER_REVISION")
  STARTED=1
  serve "$REVIEWER_PORT" "$reviewer_path" reviewer.pid reviewer.log 0.7 0.8 20 '{"enable_thinking":false}' 4GB
  serve "$COUNTER_PORT" "$counter_path" counter.pid counter.log 1.0 0.95 64 '{}' 6GB
  # The key is sourced first and LiteLLM is started on its own line, so `$!` is LiteLLM itself; a
  # trailing `&` on an `&&` chain would background the whole chain and record a wrapper's pid.
  (
    set -a
    # shellcheck source=/dev/null
    . "$LAB/.env"
    set +a
    nohup "$LAB/venv/bin/litellm" --config "$LAB/litellm-$QUANT.yaml" --host 127.0.0.1 \
      --port "$GATEWAY_PORT" >> "$LAB/logs/litellm.log" 2>&1 &
    echo $! > "$LAB/logs/litellm.pid"
  )
  for _ in $(seq 1 300); do
    if curl -s -m 2 -o /dev/null "http://127.0.0.1:$REVIEWER_PORT/v1/models" &&
      curl -s -m 2 -o /dev/null "http://127.0.0.1:$COUNTER_PORT/v1/models" &&
      curl -s -m 2 -o /dev/null "http://127.0.0.1:$GATEWAY_PORT/health/liveliness"; then
      echo "lab: $QUANT pair up behind http://127.0.0.1:$GATEWAY_PORT"
      return 0
    fi
    sleep 2
  done
  echo "lab: the pair did not come up within 10 minutes; see $LAB/logs/" >&2
  cmd_stop >&2
  exit 1
}

cmd_stop() {
  for p in litellm reviewer counter; do
    [ -f "$LAB/logs/$p.pid" ] && kill "$(cat "$LAB/logs/$p.pid")" 2>/dev/null || true
    rm -f "$LAB/logs/$p.pid"
  done
  echo "lab: stopped"
}

reclaimable_gb() {
  vm_stat | awk '/Pages free/ {f=$3} /Pages inactive/ {i=$3} /Pages speculative/ {s=$3}
    /Pages purgeable/ {p=$3} END {printf "%d", (f+i+s+p)*16384/2^30}'
}

# Restarts a model server whose generation thread died (it then answers every request with 404),
# so one failure costs the reviews in flight instead of every later review of the run.
watchdog() {
  local seen_reviewer=0 seen_counter=0 died_reviewer died_counter
  while sleep 20; do
    died_reviewer=$(grep -c "generation thread died:" "$LAB/logs/reviewer.log" 2>/dev/null || true)
    died_counter=$(grep -c "generation thread died:" "$LAB/logs/counter.log" 2>/dev/null || true)
    if (( ${died_reviewer:-0} > seen_reviewer || ${died_counter:-0} > seen_counter )); then
      seen_reviewer=${died_reviewer:-0}
      seen_counter=${died_counter:-0}
      echo "$(date -u +%FT%TZ) a model server's generation thread died; restarting" \
        >> "$LAB/logs/restarts.log"
      cmd_stop >/dev/null
      sleep 10
      cmd_start "$QUANT" >> "$LAB/logs/restarts.log" 2>&1
    fi
  done
}

kill_tree() { # signal pid: signals the pid's descendants first, then the pid
  local child
  for child in $(pgrep -P "$2" 2>/dev/null || true); do
    kill_tree "$1" "$child"
  done
  kill "-$1" "$2" 2>/dev/null || true
}

# The EXIT trap of `run`. Bash also runs it on INT, TERM and HUP. It ends the gate's whole process
# tree, which a TERM to this script alone would not reach (R4130-043), then the watchdog. It stops
# the servers only if this run started them (R4130-044), and keeps the gate's exit status.
run_cleanup() {
  if [ -n "$GATE_PID" ]; then kill_tree TERM "$GATE_PID"; fi
  if [ -n "$WATCHDOG_PID" ]; then kill_tree TERM "$WATCHDOG_PID"; fi
  if [ -n "$STARTED" ]; then cmd_stop; fi
  if [ -n "$OWNS_LOCK" ]; then
    rm -f "$LAB/run.lock/pid"
    rmdir "$LAB/run.lock" 2>/dev/null || true
  fi
}

# One run per lab directory: a second run is refused before it waits for memory or touches the
# first run's servers. A lock whose owner is gone, for example after a power loss, is taken over.
take_run_lock() {
  local holder
  until mkdir "$LAB/run.lock" 2>/dev/null; do
    holder=$(cat "$LAB/run.lock/pid" 2>/dev/null || true)
    if [ -z "$holder" ]; then
      sleep 1
      holder=$(cat "$LAB/run.lock/pid" 2>/dev/null || true)
    fi
    if [ -n "$holder" ] && kill -0 "$holder" 2>/dev/null; then
      echo "lab: another run (pid $holder) is using $LAB; wait for it to finish or stop it" >&2
      exit 1
    fi
    rm -f "$LAB/run.lock/pid"
    rmdir "$LAB/run.lock" 2>/dev/null || true
  done
  echo $$ > "$LAB/run.lock/pid"
  OWNS_LOCK=1
}

cmd_run() {
  pair "$1"
  local set=${2:-}
  case "$set" in development | seeds) ;; *) echo "lab: run needs development or seeds" >&2; exit 2 ;; esac
  local stamp
  stamp=$(date -u +%Y%m%dT%H%M%SZ)
  trap run_cleanup EXIT
  take_run_lock
  until (( $(reclaimable_gb) >= MIN_FREE_GB )); do
    echo "lab: waiting for $MIN_FREE_GB GB reclaimable ($(reclaimable_gb) GB now)"
    sleep 60
  done
  local f
  for f in reviewer.log counter.log; do
    if [ -f "$LAB/logs/$f" ]; then mv "$LAB/logs/$f" "$LAB/logs/$f.prev"; fi
  done
  cmd_start "$QUANT"
  watchdog &
  WATCHDOG_PID=$!
  local iteration=()
  if [ "$set" = development ]; then iteration=(--iteration "dev-$QUANT-$stamp"); fi
  # The gate runs as a tracked background job, so a signal reaches the trap during `wait` and the
  # trap can end the gate's tree. Under `set -e`, a failed `wait` exits with the gate's status.
  (
    cd "$CHECKOUT"
    # shellcheck source=/dev/null
    set -a && . "$LAB/.env" && set +a
    export KEIKO_DEFAULT_API_KEY="$LITELLM_MASTER_KEY"
    unset LITELLM_MASTER_KEY
    exec node scripts/testing/review-quality/run.mjs --set "$set" ${iteration[@]+"${iteration[@]}"} \
      --repository "$LAB/keiko" --config "$LAB/gateway-$QUANT.json" \
      --state "$LAB/state/$QUANT-$set-$stamp" --out "$LAB/evidence/$QUANT-$stamp" \
      --reviewer "$REVIEWER_ID" --counter-checker "$COUNTER_ID"
  ) &
  GATE_PID=$!
  wait "$GATE_PID"
}

case "${1:-}" in
  setup) cmd_setup "${2:-}" ;;
  check) cmd_check "${2:-}" ;;
  start) cmd_start "${2:-}" ;;
  stop) cmd_stop ;;
  run) cmd_run "${2:-}" "${3:-}" ;;
  *)
    sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
    exit 2
    ;;
esac
