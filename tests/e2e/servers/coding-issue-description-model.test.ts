import {
  resolveCodingSafeSidecarGatewayProfile,
  selectConfiguredModel,
} from "@oscharko-dev/keiko-model-gateway";
import { describe, expect, it } from "vitest";

import {
  functionalGatewayConfig,
  functionalReadinessFetch,
} from "../../../packages/keiko-server/src/coding-runtime/productionOpenCodeBackend.functional/_support.js";
import { DELIVERY_DESCRIPTION_MODEL_ID } from "../support/coding-issue-delivery.js";
import {
  deliveryJourneyGatewayConfig,
  deliveryJourneyReadinessFetch,
} from "./coding-issue-description-model.mjs";

// The delivery journeys (#3387, #3388, #3389) compose one gateway configuration for the whole
// server: the coding runtime is admitted on it (ADR-0171) and the automatic PR description is
// generated by the same configuration's gateway. A configuration that lost the scripted coding model
// left the Workbench without a coding profile; one that lost the loopback provider left the
// description at its fallback -- each a red journey nobody could attribute to the model it named.

const PORT = 32_586;
const SCRIPTED = functionalGatewayConfig();
const SCRIPTED_MODEL = SCRIPTED.providers[0]?.modelId;

describe("delivery journey gateway configuration", () => {
  it("offers the scripted model as the coding profile the runtime resolver names", () => {
    const resolved = resolveCodingSafeSidecarGatewayProfile(
      deliveryJourneyGatewayConfig(PORT, SCRIPTED),
      SCRIPTED_MODEL === undefined ? {} : { modelId: SCRIPTED_MODEL },
    );

    expect(resolved).toMatchObject({ status: "available", modelAlias: SCRIPTED_MODEL });
  });

  it("does not offer the description model to the coding runtime", () => {
    const resolved = resolveCodingSafeSidecarGatewayProfile(
      deliveryJourneyGatewayConfig(PORT, SCRIPTED),
      { modelId: DELIVERY_DESCRIPTION_MODEL_ID },
    );

    expect(resolved.status).toBe("unavailable");
  });

  it("selects the loopback model for the generated pull-request description", () => {
    expect(
      selectConfiguredModel(deliveryJourneyGatewayConfig(PORT, SCRIPTED), { kind: "chat" }),
    ).toBe(DELIVERY_DESCRIPTION_MODEL_ID);
  });

  it("points the loopback model at the description listener", () => {
    const provider = deliveryJourneyGatewayConfig(PORT, SCRIPTED).providers.find(
      (candidate) => candidate.modelId === DELIVERY_DESCRIPTION_MODEL_ID,
    );

    expect(provider?.baseUrl).toBe(`http://127.0.0.1:${String(PORT)}/v1`);
  });
});

describe("delivery journey readiness transport", () => {
  it("answers a basic-chat probe for the description provider without a network call", async () => {
    const probe = deliveryJourneyReadinessFetch(PORT, () =>
      Promise.reject(new Error("must not be asked")),
    );

    const response = await probe(`http://127.0.0.1:${String(PORT)}/v1/chat/completions`);

    expect(response.ok).toBe(true);
    expect(await response.json()).toMatchObject({
      choices: [{ message: { role: "assistant", content: "OK" } }],
    });
  });

  it("leaves every other destination to the scripted model's own transport", async () => {
    const probe = deliveryJourneyReadinessFetch(PORT, functionalReadinessFetch);
    const scripted = SCRIPTED.providers[0]?.baseUrl ?? "";

    expect((await probe(`${scripted}/chat/completions`)).ok).toBe(true);
    await expect(probe("https://api.example.test/v1/chat/completions")).rejects.toThrow(
      "functional-readiness-destination-unknown",
    );
    await expect(probe("http://127.0.0.1:32587/v1/chat/completions")).rejects.toThrow(
      "functional-readiness-destination-unknown",
    );
  });
});
